"""End-to-end pipeline: load -> features -> classify -> risk -> report.

Writes:
  results/metrics.txt          classifier accuracy, per-class accuracy,
                               risk-score summary (all from this run)
  results/confusion_matrix.png confusion matrix of the activity classifier
  results/risk_by_activity.png mean fall-risk proxy per activity
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless: no display needed
import matplotlib.pyplot as plt
import numpy as np

from aging import data as data_mod
from aging import features as feat_mod
from aging import classify as clf_mod
from aging import risk as risk_mod

# Project root = parent of src/ (repo layout: <root>/src/aging, <root>/data, ...)
ROOT = Path(__file__).resolve().parent.parent.parent


def _plot_confusion_matrix(result: dict, names: dict[int, str], out: Path) -> None:
    cm = result["confusion_matrix"]
    labels = [names.get(c, str(c)) for c in result["class_labels"]]
    fig, ax = plt.subplots(figsize=(8, 7))
    im = ax.imshow(cm, cmap="Blues")
    ax.set_xticks(range(len(labels)), labels, rotation=45, ha="right")
    ax.set_yticks(range(len(labels)), labels)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    ax.set_title("Activity classifier confusion matrix (held-out test set)")
    # Annotate cells; white text on dark cells for readability.
    thresh = cm.max() / 2
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            ax.text(j, i, cm[i, j], ha="center", va="center",
                    color="white" if cm[i, j] > thresh else "black", fontsize=8)
    fig.colorbar(im, ax=ax, label="windows")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def _plot_risk_by_activity(summary, out: Path) -> None:
    fig, ax = plt.subplots(figsize=(9, 4.5))
    order = summary.sort_values("mean")
    ax.barh(order["name"], order["mean"], xerr=order["std"],
            color="steelblue", ecolor="gray", capsize=3)
    ax.set_xlabel("Mean fall-risk proxy score (0-1; population-relative)")
    ax.set_title("Fall-risk proxy by activity — mean ± std over windows")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def _confident_errors(result: dict, names: dict[int, str]) -> list[str]:
    """Describe the classifier's most confident mistakes (for the report)."""
    wrong = result["y_test"] != result["y_pred"]
    lines = [f"errors: {wrong.sum()} / {len(result['y_test'])} test windows"]
    if wrong.sum():
        conf_wrong = result["confidence"][wrong]
        conf_right = result["confidence"][~wrong]
        lines.append(
            f"mean confidence on errors: {conf_wrong.mean():.3f} "
            f"(vs {conf_right.mean():.3f} on correct predictions)"
        )
        # Most common true->predicted confusion pairs among errors.
        pairs: dict[tuple[int, int], int] = {}
        for t, p in zip(result["y_test"][wrong], result["y_pred"][wrong]):
            pairs[(int(t), int(p))] = pairs.get((int(t), int(p)), 0) + 1
        lines.append("top confused pairs (true -> predicted):")
        for (t, p), c in sorted(pairs.items(), key=lambda kv: -kv[1])[:5]:
            lines.append(
                f"  {names.get(t, t)} -> {names.get(p, p)}: {c} windows"
            )
    return lines


def main() -> dict:
    results_dir = ROOT / "results"
    results_dir.mkdir(exist_ok=True)

    print("Loading UniMiB SHAR (ADL split)...")
    ds = data_mod.load_windows(ROOT / "data", split="adl")
    print("  " + data_mod.describe(ds))

    print("Extracting features...")
    feats = feat_mod.extract_features(ds["X"])
    print(f"  {feats.shape[0]} windows x {feats.shape[1]} features")

    print("Training activity classifier...")
    result = clf_mod.train_classifier(feats, ds["activity"])
    print(f"  held-out accuracy: {result['accuracy']:.4f} "
          f"({result['n_train']} train / {result['n_test']} test)")

    print("Computing fall-risk proxy scores...")
    scores = risk_mod.risk_scores(feats)
    summary = risk_mod.summarize_by_activity(scores, ds["activity"], ds["names"])
    print(f"  risk score range: [{scores.min():.3f}, {scores.max():.3f}], "
          f"mean {scores.mean():.3f}")

    # --- figures ---------------------------------------------------------
    _plot_confusion_matrix(result, ds["names"], results_dir / "confusion_matrix.png")
    _plot_risk_by_activity(summary, results_dir / "risk_by_activity.png")
    print("  wrote confusion_matrix.png, risk_by_activity.png")

    # --- metrics file ----------------------------------------------------
    lines = [
        "Aging in Place — run metrics (generated by this run, not hand-written)",
        "=" * 70,
        f"dataset: UniMiB SHAR, ADL split — {data_mod.describe(ds)}",
        f"classifier: RandomForest(n_estimators=200), stratified 80/20 split",
        f"overall held-out accuracy: {result['accuracy']:.4f}",
        "",
        "per-class accuracy:",
    ]
    for label, acc in zip(result["class_labels"], result["per_class_accuracy"]):
        lines.append(f"  {ds['names'].get(int(label), label):>14}: {acc:.4f}")
    lines += ["", "error analysis:"] + _confident_errors(result, ds["names"])
    lines += [
        "",
        "fall-risk proxy score distribution (population-relative, 0-1):",
        f"  overall: mean {scores.mean():.3f}, std {scores.std():.3f}, "
        f"median {scores.median():.3f}, min {scores.min():.3f}, max {scores.max():.3f}",
        "",
        "  per activity (mean risk, sorted high -> low):",
    ]
    for _, row in summary.iterrows():
        lines.append(
            f"  {row['name']:>14}: mean {row['mean']:.3f} "
            f"(std {row['std']:.3f}, n={int(row['count'])})"
        )
    (results_dir / "metrics.txt").write_text("\n".join(lines) + "\n")
    print("  wrote metrics.txt")

    return {
        "accuracy": result["accuracy"],
        "per_class_accuracy": dict(
            zip(result["class_labels"], result["per_class_accuracy"])
        ),
        "risk_summary": summary,
        "scores": scores,
    }


if __name__ == "__main__":
    main()
